import { onHub, refreshHub } from './hub';
import type { HubInfo } from './types';

/* ============ phone QR ============
   The code is generated by the hub from its own network address (or the configured public phoneUrl) so it is always right for this
   installation. It is shown ALL THE TIME as a small badge, so people around a table that someone else is using can scan it; tapping
   the badge (or the QR button) opens a large dialog. It is hidden only when there is nothing correct to show (the hub is unreachable,
   or it listens only on this computer), never replaced by a code that would not work. */
const shortUrl = (u: string) => u.replace(/^https?:\/\//, '').replace(/[?&]src=table$/, '').replace(/\/$/, '');

export function mountQr(stage: HTMLElement, opts: { badgeText?: string; title?: string } = {}) {
  const badgeText = opts.badgeText ?? 'Scan to play', title = opts.title ?? 'Play on your phone';
  stage.insertAdjacentHTML('beforeend',
    `<button id="qrbadge" aria-label="${badgeText}" title="${badgeText}"><span class="qbi"></span><span class="qbt"></span></button>` +
    `<div id="qr" role="dialog" aria-label="${title}"><div class="qc"><button id="qx" class="tx" aria-label="Close">✕</button>` +
    `<h3></h3><div class="qimg"></div><div class="qt"><em></em><i></i></div></div></div>`);
  const badge = stage.querySelector<HTMLElement>('#qrbadge')!, badgeImg = badge.querySelector<HTMLElement>('.qbi')!;
  const dlg = stage.querySelector<HTMLElement>('#qr')!, img = dlg.querySelector<HTMLElement>('.qimg')!;
  const addr = dlg.querySelector<HTMLElement>('.qt em')!, note = dlg.querySelector<HTMLElement>('.qt i')!;
  badge.querySelector('.qbt')!.textContent = badgeText; dlg.querySelector('h3')!.textContent = title;

  const open = () => { dlg.classList.add('on'); void refreshHub(); };
  const close = () => dlg.classList.remove('on');
  badge.addEventListener('click', open);
  stage.querySelector('#bQr')?.addEventListener('click', open);
  dlg.querySelector('#qx')!.addEventListener('click', close);
  dlg.addEventListener('click', (e) => { if (e.target === dlg) close(); });

  const show = (info: HubInfo | null) => {
    if (!info) { badge.classList.remove('on'); badgeImg.innerHTML = img.innerHTML = ''; addr.textContent = 'Phone pages are not available right now'; note.textContent = ''; return; }
    if (info.phonesCanReach === false) { badge.classList.remove('on'); badgeImg.innerHTML = img.innerHTML = ''; addr.textContent = 'Phone pages are not available on this table'; note.textContent = 'The hub is only listening on this computer'; return; }
    const src = '/api/qr.svg?t=' + Date.now();
    badgeImg.innerHTML = `<img src="${src}" alt="" width="112" height="112">`;
    img.innerHTML = `<img src="${src}" alt="QR code to open the phone pages">`;
    badge.classList.add('on');
    addr.textContent = shortUrl(info.phoneUrl);
    note.textContent = info.qrNote ?? (info.phoneUrlSource === 'lan' || info.phoneUrlSource === 'advertiseHost' ? 'Use the same Wi-Fi as the table' : info.phoneUrlSource === 'localhost' ? 'No network found: check the cable or Wi-Fi' : '');
  };
  addr.textContent = 'Loading…';
  onHub(show);
  return { open, close, isOpen: () => dlg.classList.contains('on') };
}
